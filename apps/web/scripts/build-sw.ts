// Writes dist/sw.js (PLAN §6.9): a hand-written service worker with a generated precache list of
// every prerendered page, hashed asset, font, icon and the manifest. VERSION is a hash of the
// list and the file contents, so any content change produces a new worker (and "Update ready").
import { createHash } from "node:crypto";
import { readdir, readFile, stat, writeFile } from "node:fs/promises";
import { join, relative, resolve } from "node:path";

const OUT = resolve(import.meta.dirname, "..", process.env.OUT_DIR || "dist");
const EXCLUDE = [/^schema\//, /^llms\.txt$/, /^sitemap\.xml$/, /^robots\.txt$/, /\.map$/, /^\.vite\//, /^sw\.js$/, /^og\.png$/, /^testing\//, /^src\//, /^brand\/(wordmark|mark-mono|app-icon)/];

async function walk(dir: string): Promise<string[]> {
  const out: string[] = [];
  for (const name of await readdir(dir)) {
    const p = join(dir, name);
    if ((await stat(p)).isDirectory()) out.push(...(await walk(p)));
    else out.push(p);
  }
  return out;
}

const files = (await walk(OUT)).map((f) => relative(OUT, f).split("\\").join("/")).filter((f) => !EXCLUDE.some((re) => re.test(f)));
files.sort();
const urls: string[] = [];
const h = createHash("sha256");
for (const f of files) {
  h.update(f);
  h.update(await readFile(join(OUT, f)));
  // Pages are cached under their clean URL ("/verify/"), everything else under its path.
  if (f === "index.html") urls.push("/");
  else if (f.endsWith("/index.html")) urls.push(`/${f.slice(0, -"index.html".length)}`);
  else urls.push(`/${f}`);
}
const VERSION = h.digest("hex").slice(0, 16);

const sw = `// Whirlpick service worker (generated by scripts/build-sw.ts). Offline after the first load.
const VERSION = ${JSON.stringify(VERSION)};
const CACHE = "whirlpick-" + VERSION;
const PRECACHE = ${JSON.stringify(urls)};

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith("whirlpick-") && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

function timeout(ms) {
  return new Promise((_, reject) => setTimeout(() => reject(new Error("timeout")), ms));
}

async function navigation(request) {
  const cache = await caches.open(CACHE);
  try {
    const res = await Promise.race([fetch(request), timeout(3000)]);
    if (res && res.ok) {
      cache.put(request, res.clone());
      return res;
    }
    if (res && res.status === 404) return (await cache.match("/404.html")) || res;
    return res;
  } catch (e) {
    const url = new URL(request.url);
    const clean = url.pathname.endsWith("/") ? url.pathname : url.pathname + "/";
    return (
      (await cache.match(request, { ignoreSearch: true })) ||
      (await cache.match(clean)) ||
      (await cache.match("/")) ||
      Response.error()
    );
  }
}

async function cacheFirst(request) {
  const cache = await caches.open(CACHE);
  const hit = await cache.match(request);
  if (hit) return hit;
  const res = await fetch(request);
  if (res && res.ok) cache.put(request, res.clone());
  return res;
}

async function staleWhileRevalidate(request) {
  const cache = await caches.open(CACHE);
  const hit = await cache.match(request, { ignoreSearch: true });
  const fresh = fetch(request)
    .then((res) => {
      if (res && res.ok) cache.put(request, res.clone());
      return res;
    })
    .catch(() => hit);
  return hit || fresh;
}

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;
  if (req.mode === "navigate") event.respondWith(navigation(req));
  else if (url.pathname.startsWith("/assets/")) event.respondWith(cacheFirst(req));
  else event.respondWith(staleWhileRevalidate(req));
});
`;
await writeFile(join(OUT, "sw.js"), sw);
console.log(`sw.js: ${urls.length} files precached, version ${VERSION}`);
